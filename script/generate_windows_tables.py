#!/usr/bin/env python3
"""Keep the Windows port's original control data in sync with the Swift source."""
import argparse
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / 'Sources/Core/RoseTables.swift').read_text(encoding='utf-8')
arrays = re.findall(r'static let (\w+) = \[([\d,\s]+)\]', source)
if {name for name, _ in arrays} != {'radiusA', 'radiusB', 'rotation', 'frequency'}:
    raise SystemExit('Unexpected Swift table format')
output = '// Generated by script/generate_windows_tables.py; do not edit.\n'
output += '// Original ARose: W. Breyha & M. Matzl (1994–1995).\n'
output += '// Excluded from the new-code MIT grant; see THIRD_PARTY_NOTICES.md.\n'
output += '#pragma once\n#include <vector>\nnamespace arose::tables {\n'
for name, values in arrays:
    output += f'inline const std::vector<int> {name} = {{{values}}};\n'
output += '}\n'
target = root / 'Windows/RoseTables.h'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        raise SystemExit('Windows tables are stale; run script/generate_windows_tables.py')
else:
    target.write_text(output, encoding='utf-8')
